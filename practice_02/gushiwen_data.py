def _apply_meta(works: list[dict]) -> list[dict]:
    out = []
    for w in works:
        item = dict(w)
        fname = item["filename"]
        if fname in LESSON_MAP:
            item["lesson"] = LESSON_MAP[fname]
        if fname in UNIT_PATCH:
            item["unit"] = UNIT_PATCH[fname]
        out.append(item)
    return out


